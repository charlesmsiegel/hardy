def test_cas_append_repins_recreated_directory(tmp_path, cas_session, monkeypatch):
    directory = tmp_path / 'cas'
    active = cas_session(directory)
    try:
        record = active.execute('a')
        # Stop the child whose cwd is cas before replacing that directory.
        # Windows forbids renaming a directory held by a running process.
        active.close()
        directory.rename(tmp_path / 'old-cas')
        directory.mkdir()
        # Exercise the append's re-proof independently of the separate writer
        # lease, which correctly refuses replacement of its rendezvous inode.
        monkeypatch.setattr(active, '_require_owner', lambda: None)
        active._append(record)
        assert (directory / 'cells.jsonl').is_file()
        assert '"source":"a"' in (directory / 'cells.jsonl').read_text(encoding='utf-8')
    finally:
        active.close()


def test_cas_replacement_still_refuses_changed_lease(tmp_path, cas_session):
    directory = tmp_path / 'cas'
    active = cas_session(directory)
    try:
        active._journal._lease.__exit__(None, None, None)
        directory.rename(tmp_path / 'old-cas')
        directory.mkdir()
        with pytest.raises((LayoutError, CasError)):
            active.execute('a')
    finally:
        active.close()


