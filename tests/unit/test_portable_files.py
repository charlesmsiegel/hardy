@pytest.mark.parametrize('content', [None, b'legacy pid'])
def test_lock_contents_stable_and_readable_by_subprocess(tmp_path, content):
    path = tmp_path / 'writer.lock'
    if content is not None:
        path.write_bytes(content)
    expected = content or b''
    with FileLock(path):
        result = subprocess.run([sys.executable, '-c',
            'import pathlib,shutil,sys; p=pathlib.Path(sys.argv[1]); '
            'assert p.read_bytes()==bytes.fromhex(sys.argv[2]); '
            'shutil.copy2(p,p.with_suffix(".copy"))', str(path), expected.hex()],
            capture_output=True, text=True)
        assert result.returncode == 0, result.stderr
    assert path.read_bytes() == expected


def test_git_can_index_held_lock(tmp_path):
    if not shutil.which('git'):
        pytest.skip('git is unavailable')
    subprocess.run(['git', 'init', str(tmp_path)], check=True, capture_output=True)
    path = tmp_path / 'writer.lock'
    with FileLock(path):
        result = subprocess.run(['git', '-C', str(tmp_path), 'add', 'writer.lock'], capture_output=True, text=True)
        assert result.returncode == 0, result.stderr


@pytest.mark.skipif(sys.platform == 'win32', reason='symlink creation requires Windows Developer Mode')
def test_mkdir_refuses_symlink_replacement(tmp_path):
    directory = tmp_path / 'cas'
    guard = WriteGuard(directory, create=True)
    directory.rename(tmp_path / 'old')
    other = tmp_path / 'other'
    other.mkdir()
    directory.symlink_to(other, target_is_directory=True)
    with pytest.raises(LayoutError):
        guard.mkdir()
    with pytest.raises(LayoutError):
        guard.confirm()
    assert list(other.iterdir()) == []


@pytest.mark.parametrize('name', ['references.tex', 'References.tex', 'REFERENCES.tex'])
def test_session_refuses_save_and_delete_generated_bibliography(session, name):
    session.tex_root.mkdir(exist_ok=True)
    target = session.tex_root / name
    target.write_text('generated', encoding='utf-8')
    saved = session._save_latex(name, 'replacement')
    assert not saved.ok
    before_delete = target.read_bytes()
    deleted = session._delete_file(name)
    assert not deleted.ok
    assert 'generated by Hardy' in deleted.output
    assert target.read_bytes() == before_delete
    assert 'replacement' not in target.read_text(encoding='utf-8')


