def test_mkdir_repins_external_recreation(tmp_path):
    directory = tmp_path / 'cas'
    guard = WriteGuard(directory, create=True)
    old = directory.rename(tmp_path / 'old')
    directory.mkdir()
    assert directory.stat().st_ino != old.stat().st_ino
    with pytest.raises(LayoutError, match='identity changed'):
        guard.confirm()
    guard.mkdir()
    guard.write_bytes('cells.jsonl', b'new\n')
    assert (directory / 'cells.jsonl').read_bytes() == b'new\n'


